'use strict';
// The app's copies of the project mark, "Constellation X"
// (docs/look/logo/mark.svg, the one source; never edited here):
//   renderer/img/mark.svg      the mark as is: the header, About, the intro, the favicon
//   renderer/mark-stars.js     where its stars are, read from the SVG, for the intro's twinkle
//   build/icon.png             1024x1024 (rendered the way tools/xbox/render_logo.js does)
//   build/icon.ico             16-256 px PNG entries, for Windows
//   build/icon.icns            16-1024 px PNG entries, for macOS
// All generated (gitignored); npm start, npm run dist and the tests run this first.
//   node scripts/make-icon.js [--force]
const fs = require('node:fs');
const path = require('node:path');

const APP = path.resolve(__dirname, '..');
const SRC = path.resolve(APP, '..', 'docs', 'look', 'logo', 'mark.svg');
const OUT = {
  svg: path.join(APP, 'renderer', 'img', 'mark.svg'),
  stars: path.join(APP, 'renderer', 'mark-stars.js'),
  png: path.join(APP, 'build', 'icon.png'),
  ico: path.join(APP, 'build', 'icon.ico'),
  icns: path.join(APP, 'build', 'icon.icns'),
};

/** the stars' centres and sizes in the mark's 512 viewBox: its white/green star cores (r >= 5) */
function starsOf(svg) {
  const out = [];
  const re = /<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="(#[0-9a-fA-F]{6})"/g;
  let m;
  while ((m = re.exec(svg))) {
    const r = Number(m[3]);
    if (r >= 5) out.push({ x: Number(m[1]), y: Number(m[2]), r, c: m[4].toLowerCase() });
  }
  return out;
}

function ico(pngs) {
  // ICONDIR + one ICONDIRENTRY a size, each image a PNG (Windows Vista and later)
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(pngs.length, 4);
  let off = head.length;
  pngs.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(size >= 256 ? 0 : size, e);
    head.writeUInt8(size >= 256 ? 0 : size, e + 1);
    head.writeUInt16LE(1, e + 4);
    head.writeUInt16LE(32, e + 6);
    head.writeUInt32LE(data.length, e + 8);
    head.writeUInt32LE(off, e + 12);
    off += data.length;
  });
  return Buffer.concat([head, ...pngs.map(([, d]) => d)]);
}

function icns(pngs) {
  // 'icns' + length, then one PNG chunk a type
  const TYPES = { 16: 'icp4', 32: 'icp5', 64: 'icp6', 128: 'ic07', 256: 'ic08', 512: 'ic09', 1024: 'ic10' };
  const chunks = pngs.filter(([s]) => TYPES[s]).map(([s, d]) => {
    const h = Buffer.alloc(8);
    h.write(TYPES[s], 0, 'latin1');
    h.writeUInt32BE(d.length + 8, 4);
    return Buffer.concat([h, d]);
  });
  const h = Buffer.alloc(8);
  h.write('icns', 0, 'latin1');
  h.writeUInt32BE(8 + chunks.reduce((n, c) => n + c.length, 0), 4);
  return Buffer.concat([h, ...chunks]);
}

function main() {
  const force = process.argv.includes('--force');
  const svg = fs.readFileSync(SRC, 'utf8');
  for (const f of Object.values(OUT)) fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(OUT.svg, svg);
  fs.writeFileSync(OUT.stars, `// generated by scripts/make-icon.js from docs/look/logo/mark.svg\nwindow.MARK_STARS = ${JSON.stringify(starsOf(svg))};\n`);
  const fresh = (f) => !force && fs.existsSync(f) && fs.statSync(f).mtimeMs >= fs.statSync(SRC).mtimeMs;
  if (fresh(OUT.png) && fresh(OUT.ico) && fresh(OUT.icns)) return;
  let Resvg;
  try {
    ({ Resvg } = require('@resvg/resvg-js'));
  } catch {
    console.error('make-icon: @resvg/resvg-js is missing: run npm install in app/.');
    process.exit(1);
  }
  const render = (size) => new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng();
  const sizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024];
  const pngs = sizes.map((s) => [s, render(s)]);
  fs.writeFileSync(OUT.png, pngs.find(([s]) => s === 1024)[1]);
  fs.writeFileSync(OUT.ico, ico(pngs.filter(([s]) => s <= 256)));
  fs.writeFileSync(OUT.icns, icns(pngs));
  console.log('make-icon: build/icon.png, icon.ico, icon.icns from docs/look/logo/mark.svg');
}

if (require.main === module) main();
module.exports = { starsOf, ico, icns };
