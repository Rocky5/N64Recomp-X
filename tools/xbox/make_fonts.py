#!/usr/bin/env python3
"""The loading screen's type (PLAN.md 5.5, the "deep space" title card the
maintainer approved on 2026-10-18): Sora (SIL OFL 1.1, xbox/assets/fonts/)
rasterised once here into 4-bit coverage tables the CPU blends on the
console, written to xbox/src/hw/xhw_fonts.inc (committed: the build needs no
FreeType). Run again after changing a size or weight:

    python tools/xbox/make_fonts.py

Each face: Latin-1 (32..255; codepoints the font lacks are left out), the
advance in quarter pixels, the glyph's box against the pen on the baseline,
rows of two pixels a byte (high nibble left). No kerning."""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
TTF = ROOT / 'xbox/assets/fonts/Sora[wght].ttf'
OUT = ROOT / 'xbox/src/hw/xhw_fonts.inc'

# (C name, pixel size, weight): the CSS px of the approved mockup
FACES = [
    ('xf_label', 12, 600),     # TECHPROGABE PRESENTS, chips, the step count
    ('xf_body', 13, 500),      # the footer, a card's lines
    ('xf_stage', 14, 600),     # the stage label
    ('xf_title2', 32, 700),    # a title too long for 46 px, a card's title
    ('xf_title', 46, 700),     # the game's title
]


def face(name, size, weight):
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([weight])
    asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    cmap = set()
    try:
        from fontTools.ttLib import TTFont   # optional: which codepoints the font has
        cmap = set(TTFont(str(TTF)).getBestCmap())
    except ImportError:
        cmap = None
    for cp in range(32, 256):
        ch = chr(cp)
        if (cmap is not None and cp not in cmap) or 0x7F <= cp < 0xA0:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(f.getlength(ch) * 4)
        l, t, r, b = f.getbbox(ch, anchor='ls')
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            glyphs.append((0, 0, 0, 0, adv, 0))
            continue
        im = Image.new('L', (w + 8, h + 8), 0)
        ImageDraw.Draw(im).text((4 - l, 4 - t), ch, font=f, fill=255, anchor='ls')
        im = im.crop((4, 4, 4 + w, 4 + h))
        off = len(bits)
        px = im.tobytes()
        for y in range(h):
            row = px[y * w:(y + 1) * w]
            for x in range(0, w, 2):
                a = (row[x] + 8) // 17
                c = (row[x + 1] + 8) // 17 if x + 1 < w else 0
                bits.append(a << 4 | c)
        glyphs.append((w, h, l, t, adv, off))
    out = [f'/* {name}: Sora {weight} at {size} px, ascent {asc}, descent {desc} */']
    out.append(f'static const uint8_t {name}_bits[{len(bits)}] = {{')
    for i in range(0, len(bits), 24):
        out.append('    ' + ', '.join(f'0x{v:02x}' for v in bits[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const xf_glyph {name}_glyphs[224] = {{')
    for i in range(0, 224, 4):
        out.append('    ' + ' '.join(f'{{{w}, {h}, {l}, {t}, {a}, {o}}},' for (w, h, l, t, a, o) in glyphs[i:i + 4]))
    out.append('};')
    out.append(f'static const xf_font {name} = {{ {size}, {asc}, {desc}, {name}_glyphs, {name}_bits }};')
    return out, len(bits)


def main():
    lines = ['/* xhw_fonts.inc - generated by tools/xbox/make_fonts.py from xbox/assets/fonts/Sora[wght].ttf',
             ' * (Copyright 2019 The Sora Project Authors, SIL Open Font License 1.1: xbox/assets/fonts/OFL.txt).',
             ' * Do not edit: run the script. Included by xhw_splash_draw.c. */']
    total = 0
    for spec in FACES:
        o, n = face(*spec)
        lines += o
        total += n
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'make_fonts: {len(FACES)} faces, {total} bytes of coverage -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
