#!/usr/bin/env python3
"""N64Recomp-X's dashboard icon: a rounded tile in the loading screen's
palette (the navy gradient with a teal and a violet band, PLAN.md 5.5), a
chunky green "X" (the siblings' Xbox-green tag) and a row of chevrons for
"recompiled", with a navy rim.

  tools/xbox/make_logo.py <out.png> [size]

Drawn from scratch with Pillow shapes only (no fonts, no game or console
art), so it lives in the repo and is the same on every machine.
xbox/assets/logo.png is generated by this; it is the icon of the platform
build and of any game pack without an icon.png of its own.
tools/xbox/xbe_sections.py turns it into the XBE's $$XTIMAGE (128x128 DXT1,
1-bit alpha): one opaque rounded tile with a hard edge, nothing outside it.
"""
import math
import sys

from PIL import Image, ImageDraw, ImageFilter

S = 1024   # work size, downscaled at the end for smooth edges
NAVY_TOP = (14, 22, 52)
NAVY_BOTTOM = (6, 10, 28)
RIM = (40, 60, 120)
GREEN_HI = (164, 230, 110)
GREEN_LO = (60, 160, 70)


def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def tile():
    img = Image.new("RGB", (S, S))
    px = img.load()
    for y in range(S):
        base = lerp(NAVY_TOP, NAVY_BOTTOM, y / (S - 1))
        for x in range(S):
            # two soft diagonal bands, as the loading screen's aurora
            t = math.sin((x * 0.9 + y * 1.4) / S * math.pi * 2.0 + 0.6)
            v = math.sin((x * 1.3 - y * 0.6) / S * math.pi * 2.0 + 2.1)
            a, b = max(0.0, t) ** 4, max(0.0, v) ** 4
            px[x, y] = (int(base[0] + 6 * a + 40 * b), int(base[1] + 70 * a + 14 * b), int(base[2] + 70 * a + 60 * b))
    return img


def stroke_mask(p0, p1, width):
    m = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(m)
    d.line([p0, p1], fill=255, width=width)
    r = width // 2
    for p in (p0, p1):
        d.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=255)
    return m


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "logo.png"
    size = int(sys.argv[2]) if len(sys.argv) > 2 else 256
    img = tile().convert("RGBA")
    # the X: two thick rounded strokes, green gradient, navy shadow
    x_mask = Image.new("L", (S, S), 0)
    for p0, p1 in (((430, 250), (800, 770)), ((800, 250), (430, 770))):
        x_mask = Image.composite(Image.new("L", (S, S), 255), x_mask, stroke_mask(p0, p1, 150))
    grad = Image.new("RGBA", (S, S))
    gp = grad.load()
    for y in range(S):
        c = lerp(GREEN_HI, GREEN_LO, y / (S - 1))
        for x in range(S):
            gp[x, y] = (*c, 255)
    shadow = Image.new("RGBA", (S, S), (2, 4, 12, 255))
    img.paste(shadow, (24, 28), x_mask.filter(ImageFilter.GaussianBlur(10)))
    img.paste(grad, (0, 0), x_mask)
    # the chevrons: >>> on the left, pale teal
    d = ImageDraw.Draw(img)
    for i in range(3):
        x0 = 150 + i * 80
        d.line([(x0, 420), (x0 + 60, 510), (x0, 600)], fill=(150, 210, 220, 255), width=34, joint="curve")
    # the tile's silhouette: rounded corners and a rim
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle([16, 16, S - 16, S - 16], radius=170, fill=255)
    rim = Image.new("L", (S, S), 0)
    ImageDraw.Draw(rim).rounded_rectangle([16, 16, S - 16, S - 16], radius=170, outline=255, width=26)
    img.paste(Image.new("RGBA", (S, S), (*RIM, 255)), (0, 0), rim)
    final = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    final.paste(img, (0, 0), mask)
    final = final.resize((size, size), Image.LANCZOS)
    a = final.getchannel("A").point(lambda v: 255 if v >= 128 else 0)   # 1-bit alpha for DXT1
    final.putalpha(a)
    final.save(out, "PNG")
    print(f"wrote {out} ({size}x{size})")


if __name__ == "__main__":
    main()
