#!/usr/bin/env python3
"""Symbol files for N64Recomp (PLAN.md 4.2): sections and functions, the
facts a game pack holds about its ROM's code.

  tools/xbox/syms_tools.py from-splat <decomp> <rom.z64> <version> <out.syms.toml> [--work DIR]
  tools/xbox/syms_tools.py check <syms.toml>

from-splat: a splat-based decomp's own config (config/<version>/*.yaml and
its symbol_addrs files), run once with every C subsegment taken as asm, so
spimdisasm finds every function in the ROM's code (the decomp's names where
its symbol files have them, func_XXXXXXXX where they don't). The functions'
starts and sizes come from the disassembly, not from a build: no IDO and no
MIPS binutils needed, on any OS. The output is N64Recomp's symbol format
(`[[section]] name/rom/vram/size`, `functions = [{name, vram, size}]`),
what `N64Recomp --dump-context` writes from an ELF. The ROM is read, never
written into the output: only addresses, sizes and names are.
The decomp's config needs splat at the version its requirements.txt pins
(PW64: splat64[mips]==0.39.1, in a venv: see docs/toolchain.md).

check: the file parses, functions are inside their sections, aligned and
never overlap (tools/xbox/test_syms.py runs it on every committed file).
"""
import argparse
import pathlib
import re
import shutil
import subprocess
import sys
import tomllib

GLABEL = re.compile(r'^\s*(?:glabel|dlabel_func|\.globl)\s+(\S+)')
INSN = re.compile(r'^\s*/\*\s*([0-9A-Fa-f]+)\s+([0-9A-Fa-f]{8})\s+[0-9A-Fa-f]{8}\s*\*/')
END = re.compile(r'^\s*(?:endlabel|\.end)\s+(\S+)')


def code_segments(yaml_text):
    """[(name, rom, vram, rom_end)] for the top-level `type: code` segments"""
    import yaml
    segs = yaml.safe_load(yaml_text)['segments']
    starts = []
    for s in segs:
        if isinstance(s, dict):
            starts.append(s.get('start'))
        elif isinstance(s, list):
            starts.append(s[0])
    out = []
    for i, s in enumerate(segs):
        if isinstance(s, dict) and s.get('type') == 'code':
            end = next(x for x in starts[i + 1:] if x is not None)
            out.append((s['name'], s['start'], s['vram'], end))
    return out


def all_asm(yaml_text, work):
    """the config with every C subsegment as asm, and the paths moved into work"""
    t = re.sub(r'(\[\s*0x[0-9A-Fa-f]+\s*,\s*)c(\s*,)', r'\1asm\2', yaml_text)
    t = re.sub(r'^(\s*base_path:\s*).*$', lambda m: f'{m.group(1)}{work.as_posix()}', t, flags=re.M)
    for key, val in (('create_asm_dependencies', 'False'), ('migrate_rodata_to_functions', 'False'),
                     ('ld_dependencies', 'False')):
        t = re.sub(rf'^(\s*{key}:\s*).*$', lambda m: f'{m.group(1)}{val}', t, flags=re.M)
    return t


def run_splat(decomp, rom, version, work, python):
    cfg = decomp / 'config' / version
    yml = next(cfg.glob('*.yaml'))
    if work.exists():
        shutil.rmtree(work)
    (work / 'config').mkdir(parents=True)
    shutil.copytree(cfg, work / 'config' / version)
    text = yml.read_text(encoding='utf-8')
    target = re.search(r'^\s*target_path:\s*(\S+)', text, re.M).group(1)
    shutil.copy2(rom, work / target)
    if (decomp / 'tools/splat_ext').is_dir():
        shutil.copytree(decomp / 'tools/splat_ext', work / 'tools/splat_ext')
    out = work / 'config' / version / yml.name
    out.write_text(all_asm(text, work), encoding='utf-8')
    r = subprocess.run([python, '-m', 'splat', 'split', str(out)], cwd=work, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'splat failed:\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}')
    return text


def functions_from_asm(asm_dir):
    """{vram: (name, size)} from spimdisasm's output"""
    funcs = {}
    for s in sorted(asm_dir.rglob('*.s')):
        cur, start, last = None, None, None
        def close():
            if cur is not None and start is not None:
                funcs[start] = (cur, last + 4 - start)
        for line in s.read_text(encoding='utf-8', errors='replace').splitlines():
            m = GLABEL.match(line)
            if m:
                close()
                cur, start, last = m.group(1), None, None
                continue
            m = INSN.match(line)
            if m and cur is not None:
                vram = int(m.group(2), 16)
                if start is None:
                    start = vram
                last = vram
                continue
            if END.match(line):
                close()
                cur, start = None, None
        close()
    return funcs


def write_toml(segments, funcs, out, source):
    lines = [f'# {source}', '# Generated by tools/xbox/syms_tools.py from-splat: addresses, sizes and names only.', '']
    total = 0
    for name, rom, vram, end in segments:
        size = end - rom
        fs = sorted((v, n, sz) for v, (n, sz) in funcs.items() if vram <= v < vram + size)
        total += len(fs)
        lines += ['[[section]]', f'name = ".{name}"', f'rom = 0x{rom:08X}', f'vram = 0x{vram:08X}', f'size = 0x{size:X}',
                  '', 'functions = [']
        lines += [f'    {{ name = "{n}", vram = 0x{v:08X}, size = 0x{sz:X} }},' for v, n, sz in fs]
        lines += [']', '']
    pathlib.Path(out).write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    return total


def check(path):
    t = tomllib.loads(pathlib.Path(path).read_text(encoding='utf-8'))
    errors, nf = [], 0
    secs = t.get('section', [])
    for s in secs:
        prev_end = s['vram']
        for f in sorted(s.get('functions', []), key=lambda f: f['vram']):
            nf += 1
            if f['vram'] % 4 or f['size'] % 4 or f['size'] == 0:
                errors.append(f"{f['name']}: unaligned or empty ({f['vram']:08X}, {f['size']:#x})")
            if f['vram'] < prev_end:
                errors.append(f"{f['name']} at {f['vram']:08X} overlaps the function before it")
            if f['vram'] + f['size'] > s['vram'] + s['size']:
                errors.append(f"{f['name']} runs past its section {s['name']}")
            prev_end = f['vram'] + f['size']
    for a, b in zip(sorted(secs, key=lambda s: s['rom']), sorted(secs, key=lambda s: s['rom'])[1:]):
        if a['rom'] + a['size'] > b['rom']:
            errors.append(f"sections {a['name']} and {b['name']} overlap in the ROM")
    return nf, errors


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    f = sub.add_parser('from-splat')
    f.add_argument('decomp', type=pathlib.Path)
    f.add_argument('rom', type=pathlib.Path)
    f.add_argument('version')
    f.add_argument('out')
    f.add_argument('--work', type=pathlib.Path, default=pathlib.Path('build-host/splat'))
    f.add_argument('--python', default=sys.executable, help='the Python that has the pinned splat')
    c = sub.add_parser('check')
    c.add_argument('syms')
    a = ap.parse_args()
    if a.cmd == 'check':
        n, errors = check(a.syms)
        for e in errors:
            print('  ' + e)
        print(f'{a.syms}: {n} functions, {len(errors)} problem(s)')
        return 1 if errors else 0
    work = a.work.resolve()
    text = run_splat(a.decomp.resolve(), a.rom, a.version, work, a.python)
    segments = code_segments(text)
    funcs = functions_from_asm(work / 'asm')
    rev = subprocess.run(['git', '-C', str(a.decomp), 'rev-parse', '--short', 'HEAD'], capture_output=True,
                         text=True).stdout.strip()
    n = write_toml(segments, funcs, a.out, f'From the {a.decomp.name} decomp at {rev or "?"} ({a.version}), its splat '
                   'config with every C file taken as asm.')
    print(f'{a.out}: {len(segments)} sections, {n} functions')
    nf, errors = check(a.out)
    for e in errors[:20]:
        print('  ' + e)
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
